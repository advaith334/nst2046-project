"""Command line: memsyco validate | render-prompts | run | report | rating-sheet | agreement | list-models."""

from __future__ import annotations

import json
import urllib.request
from datetime import datetime
from pathlib import Path

import typer
from dotenv import load_dotenv

from .conditions import option_map, render
from .config import load_cases, load_config, load_models
from .memory import MemoryStore
from .schema import FACTUAL_CONDITIONS, USEFUL_CONDITIONS

app = typer.Typer(add_completion=False, no_args_is_help=True)
DEFAULT_CONFIG = Path("config/pilot.yaml")


def _all_cases(config: Path):
    cfg = load_config(config)
    return cfg, load_cases(cfg.case_files + cfg.useful_memory_files)


@app.command()
def validate(config: Path = DEFAULT_CONFIG) -> None:
    """Check every case file and the model set parse, and report verification status."""
    cfg, cases = _all_cases(config)
    models = load_models(cfg.models_file, cfg.model_set)
    drafts = [c.id for c in cases if c.status != "verified"]
    typer.echo(f"{len(cases)} cases OK ({len(drafts)} still draft), {len(models)} models in set '{cfg.model_set}'")


@app.command("render-prompts")
def render_prompts(case_id: str = "pilot_canberra", useful_case_id: str = "useful_vegetarian",
                   config: Path = DEFAULT_CONFIG, out: Path = Path("docs/prompts.md")) -> None:
    """Write the exact prompt for every condition of one factual and one useful-memory case."""
    _, cases = _all_cases(config)
    by_id = {c.id: c for c in cases}
    store = MemoryStore.from_cases(cases)
    lines = [
        "# Exact prompts by condition",
        "",
        "Generated by `memsyco render-prompts` from the templates in `src/memsyco/prompts/`. "
        "Options are shown in canonical order here; in runs they are shuffled per case and repetition "
        "(the same order for every condition and model).",
        "",
    ]
    for cid, conditions in ((case_id, FACTUAL_CONDITIONS), (useful_case_id, USEFUL_CONDITIONS)):
        case = by_id[cid]
        omap = option_map(case, None)
        lines += [f"## Case `{cid}`", ""]
        for cond in conditions:
            r = render(case, cond, store, omap)
            lines += [f"### `{cond.value}`", "", "**system**", "", "```text", r.system, "```", "",
                      "**user**", "", "```text", r.user, "```", ""]
        r = render(case, conditions[1], store, omap)
        lines += [f"### Completion-mode (base model) prompt for `{conditions[1].value}`", "",
                  "```text", r.prompt, "```", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    typer.echo(f"wrote {out}")


@app.command()
def run(config: Path = DEFAULT_CONFIG, dry_run: bool = False, run_id: str | None = None,
        limit: int | None = None, runs_dir: Path = Path("runs")) -> None:
    """Run every trial in the config (resumes an existing run_id), then write the report."""
    from .client import FakeClient, OpenAICompatClient
    from .report import write_report
    from .runner import run as run_trials

    load_dotenv()
    cfg, cases = _all_cases(config)
    models = load_models(cfg.models_file, cfg.model_set)
    run_id = run_id or f"{datetime.now():%Y%m%d-%H%M%S}-{cfg.name}{'-dry' if dry_run else ''}"
    if dry_run:
        client = FakeClient()
    else:
        client = OpenAICompatClient(base_url=cfg.base_url) if cfg.base_url else OpenAICompatClient()
    out_dir = runs_dir / run_id
    run_trials(cfg, cases, models, client, out_dir, run_id, limit=limit, dry_run=dry_run)
    write_report(out_dir, {c.id: c for c in cases})
    typer.echo(f"results in {out_dir}/ (summary.md, raw_table.csv, trials.jsonl)")


@app.command()
def report(run_dir: Path, config: Path = DEFAULT_CONFIG) -> None:
    """Rebuild raw_table.csv, summary.csv and summary.md for a run."""
    from .report import write_report

    _, cases = _all_cases(config)
    write_report(run_dir, {c.id: c for c in cases})
    typer.echo((run_dir / "summary.md").read_text())


@app.command("rating-sheet")
def rating_sheet_cmd(run_dir: Path, sample: int | None = None, config: Path = DEFAULT_CONFIG) -> None:
    """Export a blinded sheet for two raters (no model or condition) plus a separate key."""
    from .report import load_trials, raw_table
    from .score import rating_sheet

    _, cases = _all_cases(config)
    by_id = {c.id: c for c in cases}
    raw = raw_table(load_trials(run_dir / "trials.jsonl"), by_id)
    sheet, key = rating_sheet(raw, by_id, run_dir, sample=sample)
    typer.echo(f"wrote {sheet} and {key} — give raters copies of the sheet only")


@app.command()
def agreement(rater_a: Path, rater_b: Path) -> None:
    """Percent agreement and Cohen's kappa per rating column."""
    from .report import to_markdown
    from .score import agreement as agree

    typer.echo(to_markdown(agree(rater_a, rater_b)))


@app.command("list-models")
def list_models(search: str = "", logprobs_only: bool = False) -> None:
    """List OpenRouter models (public catalogue) with logprob support."""
    with urllib.request.urlopen("https://openrouter.ai/api/v1/models", timeout=30) as resp:
        data = json.load(resp)["data"]
    for m in sorted(data, key=lambda m: m["id"]):
        params = m.get("supported_parameters") or []
        has_lp = "logprobs" in params
        if search.lower() not in m["id"].lower() or (logprobs_only and not has_lp):
            continue
        price = m.get("pricing", {})
        typer.echo(f"{'LP' if has_lp else '  '}  {m['id']:<55} in {price.get('prompt')}  out {price.get('completion')}")


if __name__ == "__main__":
    app()
