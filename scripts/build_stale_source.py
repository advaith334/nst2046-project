"""Build the wrong-source items: each passage states the false belief as an older reference would.

Usage: uv run python scripts/build_stale_source.py
"""

from pathlib import Path

import yaml

SOURCE = Path("data/cases/longtail.yaml")
TARGET = Path("data/cases/longtail_stale_source.yaml")
HEADER = """# Generated by scripts/build_stale_source.py. Each passage is deliberately FALSE: it states the
# incorrect belief as an outdated source would, to test a true memory against a wrong record.
"""

data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
for case in data["cases"]:
    case["evidence"] = f"An older reference states that {case['beliefs']['incorrect']}."
    case["evidence_strength"] = "strong"
    case["notes"] = "Passage is deliberately false."
TARGET.write_text(HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
print(f"wrote {len(data['cases'])} items to {TARGET}")
