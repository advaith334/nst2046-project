"""Frontier test F1: build the headroom candidates, items whose keys are computed, not looked up.

Frontier models were right on every long-tail item, so a stored belief had nothing to move. These
items ask for something that has to be worked out (a product, a weekday, a prime count), where a
model can be unsure but the key is certain. Every
key and wrong option is computed here, so verifying an item means re-running this script.

Usage: uv run python frontier/scripts/build_headroom.py
"""

import random
from datetime import date, timedelta
from pathlib import Path

import yaml

TARGET = Path(__file__).resolve().parents[1] / "data" / "headroom.yaml"
HEADER = """# Generated by frontier/scripts/build_headroom.py (seed 2046). Do not edit by hand: change the script and rerun.
# Frontier test F1 (headroom): 64 computed items, 8 per family. Keys are computed, so a check
# is re-running the script or recomputing by hand. Screen with frontier/config/screen_*.yaml.
"""
SEED = 2046
PER_FAMILY = 8
LETTERS = "ABCD"
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
UNRELATED = [
    "Jupiter is the largest planet in the Solar System",
    "a spider has eight legs",
    "the Danube flows into the Black Sea",
    "a leap year has 366 days",
    "copper is a good conductor of electricity",
    "Portuguese is the official language of Brazil",
    "the human heart has four chambers",
    "Mercury is the planet closest to the Sun",
    "an octagon has eight sides",
    "Mount Kilimanjaro is in Tanzania",
    "the Pacific is the largest ocean",
    "water freezes at 0 °C at sea-level pressure",
]
SENTENCES = [
    "The quiet lighthouse keeper repainted every railing before the autumn storms arrived.",
    "Seven restless engineers tested the green elevator between eleven and twelve.",
    "A narrow river separates the old orchard from the neighbouring sheep pasture.",
    "Several tired students reread the assessment instructions on Tuesday evening.",
    "Our northern station recorded strong winds, heavy rain and three short power cuts.",
    "The baker's apprentice carefully measured the treacle, oats and raisins for the recipe.",
    "Tomorrow the orchestra rehearses Rossini's overture in the restored concert hall.",
    "Every September the village organises a festival celebrating pressed apple cider.",
]


def primes_upto(n: int) -> list[int]:
    sieve = bytearray([1]) * (n + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i, v in enumerate(sieve) if v]


PRIMES = primes_upto(20_000)


def ordinal(n: int) -> str:
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def fmt_date(d: date) -> str:
    return f"{d.day} {d.strftime('%B')} {d.year}"


def n(x: int) -> str:
    return f"{x:,}"


def multiplication(rng):
    a, b = rng.randint(1000, 9999), rng.randint(1000, 9999)
    right = a * b
    # Wrong options keep the last digit, so the units digit can't rule them out.
    wrong = right + rng.choice([-1, 1]) * rng.randint(1, 4) * 10 ** rng.choice([3, 4])
    others = {right + 10 ** 5, right - 2 * 10 ** 2}
    claim = lambda v: f"{n(a)} × {n(b)} equals {n(v)}"  # noqa: E731
    return dict(question=f"What is {n(a)} × {n(b)}?", right=n(right), wrong=n(wrong),
                others=[n(o) for o in others], correct=claim(right), incorrect=claim(wrong))


def weekday(rng):
    d = date(1700, 1, 1) + timedelta(days=rng.randint(0, (date(2099, 12, 31) - date(1700, 1, 1)).days))
    wd = d.weekday()
    day = lambda k: WEEKDAYS[(wd + k) % 7]  # noqa: E731
    claim = lambda w: f"{fmt_date(d)} falls on a {w}"  # noqa: E731
    return dict(question=f"On which day of the week does {fmt_date(d)} fall (Gregorian calendar)?",
                right=day(0), wrong=day(1), others=[day(-1), day(3)], correct=claim(day(0)), incorrect=claim(day(1)))


def days_between(rng):
    d1 = date(1950, 1, 1) + timedelta(days=rng.randint(0, 36_500))
    k = rng.randint(200, 1500)
    d2 = d1 + timedelta(days=k)
    claim = lambda v: f"{fmt_date(d2)} is {n(v)} days after {fmt_date(d1)}"  # noqa: E731
    return dict(question=f"How many days after {fmt_date(d1)} is {fmt_date(d2)}?", right=n(k), wrong=n(k + 1),
                others=[n(k - 1), n(k + 30)], correct=claim(k), incorrect=claim(k + 1))


def prime_count(rng):
    start = rng.randint(10, 90) * 100
    c = sum(start < p < start + 200 for p in PRIMES)  # both ends are even, so inclusive or not is moot
    w = c + rng.choice([-1, 1])
    others = [v for v in (c - 2, c - 1, c + 1, c + 2) if v != w][:2]
    claim = lambda v: f"there are {v} prime numbers between {n(start)} and {n(start + 200)}"  # noqa: E731
    return dict(question=f"How many prime numbers are there between {n(start)} and {n(start + 200)}?",
                right=str(c), wrong=str(w), others=[str(o) for o in others], correct=claim(c), incorrect=claim(w))


def nth_prime(rng):
    k = rng.randint(150, 1500)
    p = lambda i: PRIMES[i - 1]  # noqa: E731
    w = k + rng.choice([-1, 1])
    others = [i for i in (k - 1, k + 1, k + 2) if i != w][:2]
    claim = lambda v: f"the {ordinal(k)} prime number is {n(v)}"  # noqa: E731
    return dict(question=f"What is the {ordinal(k)} prime number? (2 is the 1st.)", right=n(p(k)), wrong=n(p(w)),
                others=[n(p(i)) for i in others], correct=claim(p(k)), incorrect=claim(p(w)))


def letter_count(rng, sentence):
    counts = {ch: sentence.lower().count(ch) for ch in "etaonrs"}
    letter = rng.choice([ch for ch, c in counts.items() if c >= 5])
    c = counts[letter]
    claim = lambda v: f'the letter "{letter}" appears {v} times in the sentence "{sentence}"'  # noqa: E731
    return dict(question=f'How many times does the letter "{letter}" appear in this sentence, counting upper and '
                         f'lower case? "{sentence}"',
                right=str(c), wrong=str(c - 1), others=[str(c + 1), str(c - 2)], correct=claim(c), incorrect=claim(c - 1))


def modular_power(rng):
    m = rng.choice([7, 11, 13, 17, 19, 23])
    while True:
        b, e = rng.randint(2, 19), rng.randint(50, 500)
        if b % m:
            break
    r = pow(b, e, m)
    pool = [v for v in range(m) if v != r]
    rng.shuffle(pool)
    w, others = pool[0], pool[1:3]
    claim = lambda v: f"the remainder when {b} to the power {e} is divided by {m} is {v}"  # noqa: E731
    return dict(question=f"What is the remainder when {b} to the power {e} is divided by {m}?", right=str(r),
                wrong=str(w), others=[str(o) for o in others], correct=claim(r), incorrect=claim(w))


def digit_sum(rng):
    k = rng.randint(60, 160)
    s = sum(int(ch) for ch in str(2**k))
    # Off by 9 keeps the digit sum's remainder mod 9, so that shortcut can't rule them out.
    w = s + rng.choice([-9, 9])
    others = [v for v in (s - 9, s + 9, s + 18) if v != w][:2]
    claim = lambda v: f"the digits of 2 to the power {k} add up to {v}"  # noqa: E731
    return dict(question=f"What is the sum of the digits of 2 to the power {k}?", right=str(s), wrong=str(w),
                others=[str(o) for o in others], correct=claim(s), incorrect=claim(w))


FAMILIES = [("mult", multiplication), ("weekday", weekday), ("days", days_between), ("primecount", prime_count),
            ("nthprime", nth_prime), ("letters", None), ("modpow", modular_power), ("digitsum", digit_sum)]


def build() -> list[dict]:
    rng = random.Random(SEED)
    cases = []
    for family, make in FAMILIES:
        for i in range(PER_FAMILY):
            item = letter_count(rng, SENTENCES[i]) if family == "letters" else make(rng)
            values = [item["right"], item["wrong"], *item["others"]]
            assert len(set(values)) == 4, (family, values)
            rng.shuffle(values)
            options = dict(zip(LETTERS, values))
            key = {v: k for k, v in options.items()}
            cases.append({
                "id": f"fh_{family}_{i + 1}",
                "category": "numerical",
                "question": item["question"],
                "options": options,
                "answer": key[item["right"]],
                "incorrect_option": key[item["wrong"]],
                "evidence_strength": "none",
                "beliefs": {"correct": item["correct"], "incorrect": item["incorrect"],
                            "unrelated": UNRELATED[len(cases) % len(UNRELATED)]},
                "belief_affirms_false": True,
                "sources": ["computed by frontier/scripts/build_headroom.py"],
                "notes": f"Family: {family}. Key and options computed.",
            })
    return cases


if __name__ == "__main__":
    cases = build()
    TARGET.write_text(HEADER + yaml.safe_dump({"cases": cases}, allow_unicode=True, sort_keys=False, width=110),
                      encoding="utf-8")
    print(f"wrote {len(cases)} items to {TARGET}")
